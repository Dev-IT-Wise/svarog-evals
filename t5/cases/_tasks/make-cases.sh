#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Writes the T5 cases, <arm>-<task>/{case.yaml,scaffold.sh}, from
# preamble.md and each task's prompt.md. Every arm gets the same prompt,
# model, limits, tools and graders; only `plugins` differs. Re-run after
# editing a prompt and commit the result.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
cases=$(dirname "$here")
. "$here/lib.sh"
for task in $all_tasks; do
  for arm in superpowers svarog superpowers-svarog; do
    # v0.2's AC-7 arm, superpowers with svarog beside it: round 2 tasks only.
    case $arm-$task in superpowers-svarog-r2-*) ;; superpowers-svarog-*) continue ;; esac
    case $arm in
      superpowers) plugins='"../../plugins/superpowers", "../../plugins/t5-evidence"' ;;
      svarog) plugins='"../../plugins/svarog", "../../plugins/svarog-evidence", "../../plugins/t5-evidence"' ;;
      superpowers-svarog) plugins='"../../plugins/superpowers", "../../plugins/svarog", "../../plugins/svarog-evidence", "../../plugins/t5-evidence"' ;;
    esac
    d="$cases/$arm-$task"
    mkdir -p "$d"
    {
      echo "# SPDX-License-Identifier: MIT"
      echo "# Generated by _tasks/make-cases.sh - edit the prompts there, not here."
      echo 'schema_version: "1.1"'
      echo "name: $arm-$task"
      echo "description: T5 arm $arm on task $task."
      echo "tags: [t5, arm-$arm, task-$task]"
      echo "plugins: [$plugins]"
      echo "context:"
      echo "  scaffold_script: scaffold.sh"
      echo "execution:"
      echo "  model: claude-sonnet-5-5"
      echo "  max_turns: 150"
      echo "  timeout_seconds: 3600"
      echo "  allowed_tools: [Bash, Read, Edit, Write, Glob, Grep, Skill, Agent, TodoWrite, TaskCreate, TaskGet, TaskList, TaskUpdate, TaskStop]"
      echo "  prompt: |"
      cat "$here/preamble.md" "$here/$task/prompt.md" | sed 's/^/    /; s/^    $//'
      cat <<'GRADERS'
graders:
  - type: regex
    name: integrated-into-main
    target: {source: file, path: .eval-evidence/t5.txt}
    pattern: '^integrated yes$'
    flags: m
  - type: regex
    name: visible-tests-pass-on-main
    target: {source: file, path: .eval-evidence/t5.txt}
    pattern: '^visible-exit 0$'
    flags: m
  - type: regex
    name: hidden-acceptance-passes-on-main
    target: {source: file, path: .eval-evidence/t5.txt}
    pattern: '^hidden-exit 0$'
    flags: m
GRADERS
    } > "$d/case.yaml"
    printf '# SPDX-License-Identifier: MIT\nset -eu\n. "$(dirname "$0")/../_tasks/lib.sh"\nscaffold_run %s\n' "$task" > "$d/scaffold.sh"
  done
done
